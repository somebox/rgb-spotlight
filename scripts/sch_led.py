#!/usr/bin/env python3
"""Generate boards/led/led.kicad_sch through Konnect: the aluminium LED board.

Three HD2525 LEDs, each with its own isolated thermal island (net HEAT_x: the datasheet doesn't say whether the slug
is isolated, so the islands never join), and six wire pads for the harness to the driver board's J3
(pad order = J3 order: R+ R- G+ G- B+ B-). Mounting holes are board-only (scripts/gen_led_pcb.py).
Run from anywhere:  python3 scripts/sch_led.py
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import builder
from builder import *

builder.P = P = ROOT + "boards/led/"
SHEET = "led.kicad_sch"
WIRE = "rgb-spotlight:WirePad_2.2x3.5mm"
LEDS = [("R", "C49237857", "XL-HD2525SURC-A4", "RED"), ("G", "C49237859", "XL-HD2525UGC-A4", "GREEN"),
        ("B", "C49237860", "XL-HD2525UBC-A4", "BLUE")]

comps = []
for i, (ch, lcsc, mpn, name) in enumerate(LEDS):
    n = i + 1; X = 50.8 + 50.8 * i; Y = 76.2
    comps += [
        dict(ref=f"LED{n}", lib="rgb-spotlight:LED_HD2525", val=name, x=X, y=Y, rot=90, mirror="y", lcsc=lcsc,
             fields={"MPN": mpn}, pins={"2": f"LED{ch}_A", "1": f"LED{ch}_K", "3": f"HEAT_{ch}"}),
        dict(ref=f"TP{2 * n - 1}", lib="Connector:TestPoint", val=f"{ch}+", fp=WIRE, x=X + 15.24, y=Y - 10.16,
             pins={"1": f"LED{ch}_A"}),
        dict(ref=f"TP{2 * n}", lib="Connector:TestPoint", val=f"{ch}-", fp=WIRE, x=X + 15.24, y=Y + 10.16, rot=180,
             pins={"1": f"LED{ch}_K"}),
    ]

if __name__ == "__main__":
    reset(SHEET, paper="A4")
    txt = open(P + SHEET).read()
    open(P + SHEET, "w").write(txt.replace('\t(paper "A4")\n', '\t(paper "A4")\n\t(title_block (title "RGB Spotlight - LED board") (date "2026-10-05") (rev "2.0") '
                                         '(comment 1 "Aluminium, 1 layer. Wires to driver J3: R+ R- G+ G- B+ B-") (comment 2 "Generated by scripts/sch_led.py"))\n'))
    build(SHEET, 0, comps, {})
    txt = open(P + SHEET).read()   # wire pads are bare copper: keep them out of the BOM
    for n in range(1, 7):
        i = txt.index(f'(property "Reference" "TP{n}"'); j = txt.rfind("(symbol\n", 0, i)
        txt = txt[:j] + txt[j:i].replace("(in_bom yes)", "(in_bom no)") + txt[i:]
    open(P + SHEET, "w").write(txt)
    k = Konnect(); k.load("sch_wiring", "sch_components", "sch_batch", "sch_analysis")
    for t, x, y in [("Each LED sits on its own copper island (HEAT_R/G/B), never joined: slug isolation is not specified.", 25.4, 40.64),
                    ("Wire pads TP1-TP6 -> driver J3 pins 1-6 (R+ R- G+ G- B+ B-), 24 AWG, twisted per colour.", 25.4, 45.72)]:
        k.call("add_schematic_text", {"schematic": P + SHEET, "text": t, "x": x, "y": y})
