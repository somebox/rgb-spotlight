#!/usr/bin/env python3
"""Generate an LED board's schematic through Konnect: boards/led/led.kicad_sch, or boards/led35/led35.kicad_sch.

  led     the aluminium LED board: three HD2525 LEDs (2.5 mm), assembled by JLC.
  led35   the same board for 3.5 mm LEDs (D35), bought bare to try other colours on. Its LEDs are whatever gets
          soldered on, so they carry no part number.

Each LED has its own isolated thermal island (net HEAT_x: the datasheets don't say whether the slug is isolated, so
the islands never join), and six wire pads take the harness to the driver's LED sockets (R+ R- G+ G- B+ B-).
Mounting holes are board-only (scripts/gen_led_pcb.py).
Run from anywhere:  python3 scripts/sch_led.py [led|led35]     (default led)
"""
import os, sys, uuid
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import builder
from builder import *

WIRE = "rgb-spotlight:WirePad_2.2x3.5mm"
BOARDS = {
    "led": dict(
        sym="rgb-spotlight:LED_HD2525",
        leds=[("R", "C49237857", "XL-HD2525SURC-A4", "RED"), ("G", "C49237859", "XL-HD2525UGC-A4", "GREEN"),
              ("B", "C49237860", "XL-HD2525UBC-A4", "BLUE")],
        title='(title "RGB Spotlight - LED board") (date "2026-10-05") (rev "2.0") '
              '(comment 1 "Aluminium, 1 layer. Wires to driver J3: R+ R- G+ G- B+ B-")',
        notes=["Each LED sits on its own copper island (HEAT_R/G/B), never joined: slug isolation is not specified.",
               "Wire pads TP1-TP6 -> driver J3 pins 1-6 (R+ R- G+ G- B+ B-), 24 AWG, twisted per colour."]),
    # No rev or date: pcbkit release stamps them, and reset() keeps what it stamped.
    "led35": dict(
        sym="rgb-spotlight:LED_3535",
        leds=[("R", "", "", "LED 3535"), ("G", "", "", "LED 3535"), ("B", "", "", "LED 3535")],
        title='(title "RGB Spotlight - LED board, 3.5 mm LEDs") '
              '(comment 1 "Aluminium, 1 layer. Wires to the driver: J3 red, J4 green, J5 blue")',
        notes=["Each LED sits on its own copper island (HEAT_R/G/B), never joined: slug isolation is not specified.",
               "Wire pads: TP1/TP2 -> driver J3, TP3/TP4 -> J4, TP5/TP6 -> J5 (+ then -), 24 AWG, twisted per pair.",
               "R, G and B name the driver's channels, whatever colour is fitted. Bought bare (D35): any 3535 LED",
               "with two side pads and a centre slug. The makers mark polarity differently: diode-test each type."]),
}
KEY = sys.argv[1] if len(sys.argv) > 1 else "led"
B = BOARDS[KEY]
builder.P = P = ROOT + f"boards/{KEY}/"
SHEET = f"{KEY}.kicad_sch"

comps = []
for i, (ch, lcsc, mpn, name) in enumerate(B["leds"]):
    n = i + 1; X = 50.8 + 50.8 * i; Y = 76.2
    comps += [
        dict(ref=f"LED{n}", lib=B["sym"], val=name, x=X, y=Y, rot=90, mirror="y", lcsc=lcsc,
             fields={"MPN": mpn} if mpn else {}, pins={"2": f"LED{ch}_A", "1": f"LED{ch}_K", "3": f"HEAT_{ch}"}),
        dict(ref=f"TP{2 * n - 1}", lib="Connector:TestPoint", val=f"{ch}+", fp=WIRE, x=X + 15.24, y=Y - 10.16,
             pins={"1": f"LED{ch}_A"}),
        dict(ref=f"TP{2 * n}", lib="Connector:TestPoint", val=f"{ch}-", fp=WIRE, x=X + 15.24, y=Y + 10.16, rot=180,
             pins={"1": f"LED{ch}_K"}),
    ]

if __name__ == "__main__":
    if not os.path.exists(P + SHEET):          # a new board: a blank sheet for reset() to keep the uuid of
        open(P + SHEET, "w").write(f'(kicad_sch\n\t(version 20260306)\n\t(generator "eeschema")\n\t(uuid "{uuid.uuid4()}")\n)\n')
    reset(SHEET, paper="A4")
    txt = open(P + SHEET).read()
    if "(title_block" not in txt:              # reset() keeps a title block, with what a release stamped into it
        txt = txt.replace('\t(paper "A4")\n', '\t(paper "A4")\n\t(title_block ' + B["title"]
                          + ' (comment 2 "Generated by scripts/sch_led.py"))\n')
        open(P + SHEET, "w").write(txt)
    build(SHEET, 0, comps, {})
    txt = open(P + SHEET).read()   # wire pads are bare copper: keep them out of the BOM
    for n in range(1, 7):
        i = txt.index(f'(property "Reference" "TP{n}"'); j = txt.rfind("(symbol\n", 0, i)
        txt = txt[:j] + txt[j:i].replace("(in_bom yes)", "(in_bom no)") + txt[i:]
    open(P + SHEET, "w").write(txt)
    k = Konnect(); k.load("sch_wiring", "sch_components", "sch_batch", "sch_analysis")
    for n, t in enumerate(B["notes"]):
        k.call("add_schematic_text", {"schematic": P + SHEET, "text": t, "x": 25.4, "y": 40.64 + 5.08 * n})
