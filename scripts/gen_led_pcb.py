"""LED board (aluminium, single copper layer) from its netlist: placement, routing, thermal islands, silk. Fully generated.

  scripts/make_led_pcb.sh            (netlist export -> this script -> DRC)
  <KiCad python> scripts/gen_led_pcb.py <netlist.net> <out.kicad_pcb>

Board centre = origin, KiCad coordinates (y down), angles counter-clockwise from +x.
- Everything inside the 50 mm core (mech.CORE_D). The board edge and mounting holes come from an outline preset
  (MECH=disc50|disc55|disc60|tabs3, default disc50; scripts/mech.py); scripts/set_outline.py changes it later.
- Order as aluminium, 1 layer (only F.Cu is used; B.Cu stays empty).
- LEDs at R_LED: red 90, green 210, blue 330 deg; pads tangential (cathode on the counter-clockwise side).
- Centre hole (6.4 mm) for the six wires; their pads sit around it at R_PAD, each pair beside its LED's direction,
  and the wires solder on the front and drop straight through the hole.
- Each LED sits on its own copper island (net HEAT_x, a 100 deg sector from R_ISL_IN to R_ISL_OUT): spreads the
  slug's heat into the dielectric. The islands never touch (slug isolation is not specified).
- Mounting holes per preset: inner M3 at r = 19 mm (30 / 150 / 270 deg, between the islands), or rim holes / tabs.
"""
import math, os, re, sys
import pcbnew

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import mech
NET, OUT = sys.argv[1], sys.argv[2]
KFP = "/Applications/KiCad/KiCad.app/Contents/SharedSupport/footprints/"
PLIB = os.path.join(HERE, "..", "lib", "rgb-spotlight.pretty")
libdir = lambda lib: PLIB if lib == "rgb-spotlight" else KFP + lib + ".pretty"
mm = pcbnew.FromMM
X0, Y0 = 150.0, 100.0
V = lambda x, y: pcbnew.VECTOR2I_MM(X0 + x, Y0 + y)
# ---- parameters (mm, deg) -----------------------------------------------------------------------------------
R_BOARD = mech.CORE_R   # the core: the edge itself comes from the outline preset
R_LED = 12.0            # LED ring radius (v1: 6.7). Larger = more separated colours
D_WIRE_HOLE = 6.4       # centre cutout for 6 x 24 AWG
R_PAD = 6.2             # wire pad centres
PAD_SPREAD = 23.0       # each LED's +/- pads sit at its angle -/+ this
R_ISL_IN, R_ISL_OUT, ISL_HALF = 8.6, 22.0, 46.0
TRACK = 1.2             # LED +/- tracks (455 mA, and they carry heat too)
CH = {"R": (1, 90), "G": (2, 210), "B": (3, 330)}

polar = lambda r, a: (r * math.cos(math.radians(a)), -r * math.sin(math.radians(a)))

# ---- netlist ---------------------------------------------------------------------------------------------
t = open(NET).read()
comps = {}
for blk in re.split(r'\n\t\t\(comp\n', t.split("(libparts")[0].split("(nets")[0])[1:]:
    g = lambda pat: (re.search(pat, blk, re.S) or [None, None])[1]
    comps[g(r'\(ref "([^"]+)"\)')] = dict(
        value=g(r'\(value "([^"]*)"\)'), fp=g(r'\(footprint "([^"]+)"\)'),
        sheet=g(r'\(sheetpath\s*\(names "[^"]*"\)\s*\(tstamps "([^"]+)"\)'), ts=g(r'\n\t\t\t\(tstamps "([^"]+)"'),
        fields=dict(re.findall(r'\(field\s*\(name "([^"]+)"\)(?:\s*"([^"]*)")?\s*\)', blk)),
        no_bom='(name "exclude_from_bom")' in blk, desc=g(r'\(description "([^"]*)"\)'))
pinnet, netnames = {}, []
for blk in re.split(r'\n\t\t\(net\n', t[t.index("(nets"):])[1:]:
    name = re.search(r'\(name "([^"]*)"\)', blk).group(1)
    netnames.append(name)
    for r, pn in re.findall(r'\(ref "([^"]+)"\)\s*\(pin "([^"]+)"\)', blk):
        pinnet[(r, pn)] = name

# ---- placement ---------------------------------------------------------------------------------------------
P = {}
for ch, (n, a) in CH.items():
    P[f"LED{n}"] = (*polar(R_LED, a), (a - 90) % 360)              # rot 0 at the top: pads along x = tangential
    P[f"TP{2 * n - 1}"] = (*polar(R_PAD, a - PAD_SPREAD), (a - PAD_SPREAD - 90) % 360)   # + (anode) side: clockwise
    P[f"TP{2 * n}"] = (*polar(R_PAD, a + PAD_SPREAD), (a + PAD_SPREAD - 90) % 360)       # - (cathode) side
assert set(comps) == set(P), set(comps) ^ set(P)

from pcbkit.kicad import data_path
b = pcbnew.LoadBoard(data_path("templates", "blank.kicad_pcb"))
b.SetCopperLayerCount(2)
ds = b.GetDesignSettings()
ds.m_CopperEdgeClearance = mm(0.5); ds.m_MinClearance = mm(0.2); ds.m_TrackMinWidth = mm(0.2)
ds.m_HoleClearance = mm(0.5)
ds.m_MinSilkTextHeight = mm(0.8); ds.m_MinSilkTextThickness = mm(0.15)
nc = ds.m_NetSettings.GetDefaultNetclass()
nc.SetTrackWidth(mm(TRACK)); nc.SetClearance(mm(0.3))
tb = b.GetTitleBlock(); tb.SetTitle("RGB Spotlight - LED board"); tb.SetRevision("2.0"); tb.SetDate("2026-10-05")
tb.SetComment(0, "ALUMINIUM, 1 layer (F.Cu only). Generated by scripts/gen_led_pcb.py")
for nm in netnames:
    if b.FindNet(nm) is None:
        b.Add(pcbnew.NETINFO_ITEM(b, nm))
NETF = lambda n: b.FindNet(n) or b.FindNet("/" + n)


for ref, c in comps.items():
    lib, name = c["fp"].split(":")
    fp = pcbnew.FootprintLoad(libdir(lib), name); assert fp, c["fp"]
    fp.SetFPID(pcbnew.LIB_ID(lib, name)); fp.SetReference(ref); fp.SetValue(c["value"])
    fp.SetPath(pcbnew.KIID_PATH(c["sheet"] + c["ts"])); fp.SetSheetname("/"); fp.SetSheetfile("led.kicad_sch")
    for key, v in c["fields"].items():
        if key in ("Footprint", "Reference", "Value"):
            continue
        if not fp.HasField(key):
            fp.Add(pcbnew.PCB_FIELD(fp, fp.GetNextFieldOrdinal(), key))
        fp.GetField(key).SetText(v or ""); fp.GetField(key).SetVisible(False)
    if c["desc"] is not None and fp.HasField("Description"):
        fp.GetField("Description").SetText(c["desc"])
    fp.SetExcludedFromBOM(c["no_bom"])
    b.Add(fp)
    for pad in fp.Pads():
        n = pinnet.get((ref, pad.GetNumber()))
        if n:
            pad.SetNet(b.FindNet(n))
    x, y, r = P[ref]
    fp.SetPosition(V(x, y)); fp.SetOrientationDegrees(r)
    if ref.startswith("TP"):
        fp.Reference().SetVisible(False); fp.Value().SetVisible(False)

# wire hole: a plain cutout (a mounting-hole footprint would bring a screw-head courtyard over the wire pads)
cut = pcbnew.PCB_SHAPE(b); cut.SetShape(pcbnew.SHAPE_T_CIRCLE); cut.SetLayer(pcbnew.Edge_Cuts); cut.SetWidth(mm(0.05))
cut.SetCenter(V(0, 0)); cut.SetEnd(V(D_WIRE_HOLE / 2, 0)); b.Add(cut)
OUTLINE, n_holes, _ = mech.apply_outline(b, "led", None, X0, Y0)

# ---- routing: each LED pad straight in to its wire pad (two segments: radial, then across) ----------------------
def pad_xy(ref, num):
    p = b.FindFootprintByReference(ref).FindPadByNumber(num).GetPosition()
    return pcbnew.ToMM(p.x) - X0, pcbnew.ToMM(p.y) - Y0
def track(pts, net, w=TRACK):
    for (x1, y1), (x2, y2) in zip(pts, pts[1:]):
        tr = pcbnew.PCB_TRACK(b); tr.SetStart(V(x1, y1)); tr.SetEnd(V(x2, y2)); tr.SetWidth(mm(w))
        tr.SetLayer(pcbnew.F_Cu); tr.SetNet(net); b.Add(tr)
for ch, (n, a) in CH.items():
    for led_pad, tp in (("2", f"TP{2 * n - 1}"), ("1", f"TP{2 * n}")):
        lx, ly = pad_xy(f"LED{n}", led_pad); tx, ty = pad_xy(tp, "1")
        # leave the LED pad radially inwards at pad width (the centre thermal pad is 0.3 mm away), widen once past
        # the LED body (2.1 mm in from the pad centre), then go straight to the wire pad
        ux, uy = polar(1.0, a)
        mx, my = lx - ux * 2.1, ly - uy * 2.1
        net = b.FindFootprintByReference(tp).FindPadByNumber("1").GetNet()
        track([(lx, ly), (mx, my)], net, 0.45)
        track([(mx, my), (tx, ty)], net)

# ---- thermal islands -----------------------------------------------------------------------------------------
for ch, (n, a) in CH.items():
    z = pcbnew.ZONE(b); z.SetLayer(pcbnew.F_Cu); z.SetNet(NETF(f"HEAT_{ch}")); z.SetZoneName(f"HEAT_{ch}")
    z.SetLocalClearance(mm(0.3)); z.SetMinThickness(mm(0.3)); z.SetPadConnection(pcbnew.ZONE_CONNECTION_FULL)
    ol = z.Outline(); ol.NewOutline()
    steps = 24
    for i in range(steps + 1):
        ol.Append(*(mm(v) for v in (lambda p: (X0 + p[0], Y0 + p[1]))(polar(R_ISL_OUT, a - ISL_HALF + 2 * ISL_HALF * i / steps))))
    for i in range(steps + 1):
        ol.Append(*(mm(v) for v in (lambda p: (X0 + p[0], Y0 + p[1]))(polar(R_ISL_IN, a + ISL_HALF - 2 * ISL_HALF * i / steps))))
    b.Add(z)

# ---- silkscreen ----------------------------------------------------------------------------------------------
def text(s, x, y, size=1.0, angle=0, layer=pcbnew.F_SilkS):
    tx = pcbnew.PCB_TEXT(b); tx.SetText(s); tx.SetLayer(layer)
    tx.SetTextSize(pcbnew.VECTOR2I_MM(size, size)); tx.SetTextThickness(mm(max(0.15, size * 0.15)))
    tx.SetTextAngleDegrees(angle); tx.SetPosition(V(x, y)); b.Add(tx)
for ch, (n, a) in CH.items():
    for sign, tp in (("+", f"TP{2 * n - 1}"), ("-", f"TP{2 * n}")):
        ang = a - PAD_SPREAD if sign == "+" else a + PAD_SPREAD
        # label beside the pad, on the far side from its partner
        off = -9 if sign == "+" else 9
        text(f"{ch}{sign}", *polar(R_PAD + 0.6, ang + off * 2.2), 0.8, (ang - 90) % 360)
    text(ch, *polar(R_LED + 3.2, a), 1.2, (a - 90) % 360)
for ref in ("LED1", "LED2", "LED3"):
    b.FindFootprintByReference(ref).Reference().SetLayer(pcbnew.F_Fab)
text("RGB LED v2.0", 0, 12.2, 0.8, 90)          # in the bare gap between the green and blue islands
pcbnew.ZONE_FILLER(b).Fill(b.Zones())
pcbnew.SaveBoard(OUT, b)
print(f"led board: {len(comps)} footprints + wire cutout in the {mech.CORE_D:.0f} mm core, LEDs at r = {R_LED} mm, routed; "
      f"outline {OUTLINE}: {mech.describe(OUTLINE)}, {n_holes} holes")
